import Foundation

enum PlannerTimePolicy {
    static func mergedBusyTimes(_ intervals: [DateInterval], within range: DateInterval) -> [DateInterval] {
        let clipped = intervals.compactMap { interval -> DateInterval? in
            let start = max(interval.start, range.start), end = min(interval.end, range.end)
            return end > start ? DateInterval(start: start, end: end) : nil
        }.sorted { $0.start < $1.start }
        var result: [DateInterval] = []
        for interval in clipped {
            if let last = result.last, last.end >= interval.start {
                result[result.count - 1] = DateInterval(start: last.start, end: max(last.end, interval.end))
            } else { result.append(interval) }
        }
        return result
    }
    static func overlaps(_ suggestion: EndurancePlanSuggestion, busy: [DateInterval]) -> Bool {
        let end = suggestion.start.addingTimeInterval(Double(suggestion.minutes * 60))
        return busy.contains { $0.start < end && $0.end > suggestion.start }
    }

    /// Clock times are parsed from what the person wrote, never generated by a language model.
    /// Open-ended phrases ("after work", "after 6pm") stay empty for explicit selection.
    static func explicitWindows(in text: String) -> [EnduranceAvailabilityWindow] {
        let text = text.lowercased().replacingOccurrences(of: ".", with: "")
        let day = #"(?:weekdays?|weekends?|every day|daily|monday|tuesday|wednesday|thursday|friday|saturday|sunday|mon|tue|wed|thu|fri|sat|sun)"#
        let pattern = "(" + day + "(?:\\s*(?:,|and|&)\\s*" + day + ")*)\\s*(?:from\\s*)?(\\d{1,2})(?::(\\d{2}))?\\s*(am|pm)?\\s*(?:[–—-]|to|until)\\s*(\\d{1,2})(?::(\\d{2}))?\\s*(am|pm)?"
        guard let regex = try? NSRegularExpression(pattern: pattern) else { return [] }
        let ns = text as NSString
        var result: [EnduranceAvailabilityWindow] = []
        for match in regex.matches(in: text, range: NSRange(location: 0, length: ns.length)) {
            func part(_ n: Int) -> String { match.range(at: n).location == NSNotFound ? "" : ns.substring(with: match.range(at: n)) }
            let startSuffix = part(4).isEmpty ? part(7) : part(4)
            guard let start = minute(hour: part(2), minute: part(3), suffix: startSuffix),
                  let end = minute(hour: part(5), minute: part(6), suffix: part(7)), end > start else { continue }
            // A bare "3–4" has no reliable AM/PM meaning. 24-hour notation must be explicit.
            guard !startSuffix.isEmpty || !part(3).isEmpty || (Int(part(2)) ?? 0) >= 13,
                  !part(7).isEmpty || !part(6).isEmpty || (Int(part(5)) ?? 0) >= 13 else { continue }
            let days = part(1)
            let names = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"]
            for weekday in 1...7 {
                let included = days.contains(names[weekday - 1]) || days.contains("weekday") && weekday <= 5
                    || days.contains("weekend") && weekday >= 6 || days.contains("every day") || days.contains("daily")
                let window = EnduranceAvailabilityWindow(weekday: weekday, startMinute: start, endMinute: end)
                if included && window.isValid && !result.contains(where: { $0.weekday == weekday && $0.startMinute == start && $0.endMinute == end }) { result.append(window) }
            }
        }
        return result
    }
    private static func minute(hour: String, minute: String, suffix: String) -> Int? {
        guard var hour = Int(hour), let minute = Int(minute.isEmpty ? "0" : minute), (0..<60).contains(minute) else { return nil }
        if !suffix.isEmpty {
            guard (1...12).contains(hour) else { return nil }
            hour = hour % 12 + (suffix == "pm" ? 12 : 0)
        }
        guard (0...24).contains(hour), hour != 24 || minute == 0 else { return nil }
        return hour * 60 + minute
    }
}
